-- Oracle Database 21c XE
-- Ejecuta este script conectado como PORTFOLIO_API.
-- Las columnas IDENTITY sustituyen las secuencias y triggers heredados.

CREATE TABLE ICON (
  ID_ICON NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  TITLE_ICON VARCHAR2(80 CHAR) NOT NULL,
  URL_ICON VARCHAR2(500 CHAR) NOT NULL,
  TYPE_ICON VARCHAR2(25 CHAR) NOT NULL,
  CONSTRAINT PK_ICON PRIMARY KEY (ID_ICON),
  CONSTRAINT UQ_ICON_TITLE UNIQUE (TITLE_ICON)
);

CREATE TABLE SUBTYPE_DESCRIPTION (
  ID_SUBTYPE NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  DESCRIPTION_SUBTYPE VARCHAR2(80 CHAR) NOT NULL,
  CONSTRAINT PK_SUBTYPE_DESCRIPTION PRIMARY KEY (ID_SUBTYPE),
  CONSTRAINT UQ_SUBTYPE_DESCRIPTION UNIQUE (DESCRIPTION_SUBTYPE)
);

CREATE TABLE AUDIO (
  ID_AUDIO NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  TITLE_AUDIO VARCHAR2(80 CHAR) NOT NULL,
  URL_AUDIO VARCHAR2(500 CHAR) NOT NULL,
  TYPE_AUDIO VARCHAR2(25 CHAR) NOT NULL,
  DESCRIPTION_AUDIO VARCHAR2(500 CHAR),
  SUBTYPES_AUDIO NUMBER(10) NOT NULL,
  CONSTRAINT PK_AUDIO PRIMARY KEY (ID_AUDIO),
  CONSTRAINT FK_AUDIO_SUBTYPE
    FOREIGN KEY (SUBTYPES_AUDIO) REFERENCES SUBTYPE_DESCRIPTION (ID_SUBTYPE)
);

CREATE TABLE IMAGE (
  ID_IMAGE NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  TITLE_IMAGE VARCHAR2(80 CHAR) NOT NULL,
  URL_IMAGE VARCHAR2(500 CHAR) NOT NULL,
  TYPE_IMAGE VARCHAR2(25 CHAR) NOT NULL,
  SUBTYPES_IMAGE NUMBER(10),
  CONSTRAINT PK_IMAGE PRIMARY KEY (ID_IMAGE),
  CONSTRAINT UQ_IMAGE_TITLE UNIQUE (TITLE_IMAGE),
  CONSTRAINT FK_IMAGE_SUBTYPE
    FOREIGN KEY (SUBTYPES_IMAGE) REFERENCES SUBTYPE_DESCRIPTION (ID_SUBTYPE)
);

CREATE TABLE DEMOS (
  ID_DEMOS NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  TITLE_DEMOS VARCHAR2(100 CHAR) NOT NULL,
  URL_DEMOS VARCHAR2(500 CHAR) NOT NULL,
  CONSTRAINT PK_DEMOS PRIMARY KEY (ID_DEMOS),
  CONSTRAINT UQ_DEMOS_TITLE UNIQUE (TITLE_DEMOS)
);

CREATE TABLE IMAGE3D (
  ID_IMAGE3D NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  TITLE_IMAGE3D VARCHAR2(80 CHAR) NOT NULL,
  URL_IMAGE3D VARCHAR2(500 CHAR) NOT NULL,
  CONSTRAINT PK_IMAGE3D PRIMARY KEY (ID_IMAGE3D),
  CONSTRAINT UQ_IMAGE3D_TITLE UNIQUE (TITLE_IMAGE3D)
);

CREATE TABLE MEDIA (
  ID_MEDIA NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  TITLE_MEDIA VARCHAR2(80 CHAR) NOT NULL,
  URL_MEDIA VARCHAR2(1000 CHAR) NOT NULL,
  ICON_MEDIA NUMBER(10) NOT NULL,
  CONSTRAINT PK_MEDIA PRIMARY KEY (ID_MEDIA),
  CONSTRAINT UQ_MEDIA_TITLE UNIQUE (TITLE_MEDIA),
  CONSTRAINT FK_MEDIA_ICON FOREIGN KEY (ICON_MEDIA) REFERENCES ICON (ID_ICON)
);

CREATE INDEX IX_AUDIO_SUBTYPE ON AUDIO (SUBTYPES_AUDIO);
CREATE INDEX IX_IMAGE_SUBTYPE ON IMAGE (SUBTYPES_IMAGE);
CREATE INDEX IX_MEDIA_ICON ON MEDIA (ICON_MEDIA);
